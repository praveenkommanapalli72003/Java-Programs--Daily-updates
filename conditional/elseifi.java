public class elseifi {
    public static void main(String[] args) {
        int m = 95;
        if(m<=100 && m>=91){
            System.out.println("A grade");
        }
        else if(m<=90 && m<=81){
            System.out.println("B grade");
        }
        else if(m<=80 && m<=71){
            System.out.println("C grade");
        }
        else{
            System.out.println(" Fail ");
        }
    }
}
